// Generates src/generated/library.ts from the Franzen ComponentLibrary SVG files.
// The Illustrator exports carry a DOCTYPE with XML entities and private namespaces;
// we strip all of that and keep only plain, self-contained SVG markup.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'ComponentLibrary_files', 'svg');
const outFile = path.join(root, 'src', 'generated', 'library.ts');

const SKIP = new Set(['b-credit']);

/** @param {string} raw */
function sanitize(raw) {
  let s = raw;
  s = s.replace(/<\?xml[\s\S]*?\?>/g, '');
  s = s.replace(/<!DOCTYPE[\s\S]*?\]>/g, '');
  s = s.replace(/<!DOCTYPE[^>]*>/g, '');
  s = s.replace(/<metadata>[\s\S]*?<\/metadata>/g, '');
  s = s.replace(/<\?[\s\S]*?\?>/g, '');
  // namespace declarations that reference DTD entities
  s = s.replace(/\sxmlns:[A-Za-z0-9]+="&[^"]*?"/g, '');
  s = s.replace(/\sxmlns="&ns_svg;"/g, '');
  // private Illustrator / Adobe attributes
  s = s.replace(/\s(?:i|x|graph|a|v):[A-Za-z0-9_]+="[^"]*"/g, '');
  // Adobe private *elements* (e.g. <a:midPointStop/>) become invalid XML once the
  // namespace declaration is gone, so drop them entirely.
  s = s.replace(
    /<(?:a|i|x|graph|v):[A-Za-z0-9_]+\b[^>]*>[\s\S]*?<\/(?:a|i|x|graph|v):[A-Za-z0-9_]+>/g,
    '',
  );
  s = s.replace(/<(?:a|i|x|graph|v):[A-Za-z0-9_]+\b[^>]*\/>/g, '');
  s = s.replace(/\senable-background="[^"]*"/g, '');
  s = s.replace(/\sxml:space="preserve"/g, '');
  s = s.replace(/&ns_[A-Za-z0-9_]+;/g, '');
  s = s.replace(/\sid="__[^"]*"/g, '');
  return s.trim();
}

const files = fs
  .readdirSync(srcDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

/** Cheap well-formedness check: matching open/close tags, ignoring self-closing ones. */
function checkTags(s) {
  const stack = [];
  const re = /<(\/?)([A-Za-z_][\w.:-]*)((?:"[^"]*"|'[^']*'|[^>"'])*?)(\/?)>/g;
  let m;
  while ((m = re.exec(s))) {
    const [, close, name, , selfClose] = m;
    if (close) {
      const top = stack.pop();
      if (top !== name) return `mis-nested tag </${name}> (open: ${top ?? 'none'})`;
    } else if (!selfClose) {
      stack.push(name);
    }
  }
  return stack.length ? `unclosed <${stack[stack.length - 1]}>` : null;
}
/** @type {Record<string, {w:number,h:number,svg:string}>} */
const lib = {};
const problems = [];

/** Shapes drawn in-house (assets/parts) sit next to the library ones. */
const ownDir = path.join(root, 'assets', 'parts');
const sources = files
  .filter((f) => !SKIP.has(path.basename(f, '.svg')))
  .map((f) => ({ key: path.basename(f, '.svg'), file: path.join(srcDir, f) }));
if (fs.existsSync(ownDir)) {
  for (const f of fs.readdirSync(ownDir).filter((n) => n.endsWith('.svg')).sort()) {
    sources.push({ key: path.basename(f, '.svg'), file: path.join(ownDir, f) });
  }
}

for (const { key, file } of sources) {
  const sanitized = sanitize(fs.readFileSync(file, 'utf8'));

  const vbMatch = /viewBox="([^"]+)"/.exec(sanitized);
  if (!vbMatch) {
    problems.push(`${key}: no viewBox`);
    continue;
  }
  const vb = vbMatch[1].trim().split(/[\s,]+/).map(Number);
  if (vb.length !== 4 || vb.some((n) => !Number.isFinite(n))) {
    problems.push(`${key}: bad viewBox ${vbMatch[1]}`);
    continue;
  }

  const open = sanitized.indexOf('<svg');
  const gt = sanitized.indexOf('>', open);
  const close = sanitized.lastIndexOf('</svg>');
  if (open < 0 || gt < 0 || close < 0) {
    problems.push(`${key}: no svg element`);
    continue;
  }
  const inner = sanitized.slice(gt + 1, close).trim();

  const leftover = inner.match(/&[A-Za-z_][A-Za-z0-9_.-]*;/g);
  if (leftover) problems.push(`${key}: leftover entities ${[...new Set(leftover)].join(',')}`);
  const prefixed = inner.match(/<[A-Za-z_][\w.-]*:[A-Za-z0-9_]/g);
  if (prefixed) problems.push(`${key}: prefixed element ${[...new Set(prefixed)].join(',')}`);
  const nest = checkTags(inner);
  if (nest) problems.push(`${key}: ${nest}`);
  if (/<svg[\s>]/.test(inner)) problems.push(`${key}: nested svg`);
  if (/<text[\s>]/.test(inner)) problems.push(`${key}: has text`);
  if (/xlink:href|href=/.test(inner)) problems.push(`${key}: has href`);
  if (/url\(#(?!)/.test(inner)) {
    /* gradient url(#id) references are fine, they get prefixed at render time */
  }

  lib[key] = { w: vb[2], h: vb[3], svg: inner };
}

const header = `// AUTO-GENERATED by scripts/gen-library.mjs — do not edit by hand.
// Vector artwork: ComponentLibrary by Alexander Franzen (CC BY-NC 3.0).
// https://www.gwoptics.org/component_library/
`;
const body = `export interface LibShape { w: number; h: number; svg: string }\n\nexport const LIBRARY: Record<string, LibShape> = ${JSON.stringify(
  lib,
  null,
  1,
)};\n`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, header + body, 'utf8');

const keys = Object.keys(lib);
console.log(`wrote ${keys.length} shapes -> ${path.relative(root, outFile)}`);
console.log(`bytes: ${fs.statSync(outFile).size}`);
if (problems.length) {
  console.log('--- problems ---');
  for (const p of problems) console.log('  ' + p);
}
console.log(keys.join(' '));
